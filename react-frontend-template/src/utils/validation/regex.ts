export const REGEX = {
  EMAIL:      /^[^\s@]+@[^\s@]+\.[^\s@]+$/,
  PASSWORD:   /^(?=.*[a-zA-Z])(?=.*\d)(?=.*[!@#$%^&*()_+\-=[\]{};':"\\|,.<>/?]).{8,}$/,
  PHONE_KR:   /^01[016789]-?\d{3,4}-?\d{4}$/,
  NUMBER:     /^\d+$/,
  ALPHA:      /^[a-zA-Z]+$/,
  ALPHA_NUM:  /^[a-zA-Z0-9]+$/,
  KOREAN:     /^[가-힣]+$/,
  URL:        /^(https?:\/\/)?([\w.-]+)\.([a-z]{2,})(\/\S*)?$/i,
  POSTAL_KR:  /^\d{5}$/,
} as const;
